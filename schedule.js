(function () {
  var KEY = 'logistics_shared_custom_v1';   // waiting on this computer
  var CACHE = 'logistics_sheet_cache_v1';   // last copy of the online list
  var WKEY = 'logistics_sheet_key';         // secret word (kept on this computer only)
  var BASE = window.BASE_SCHEDULE;

  function jget(k, def) { try { var v = JSON.parse(localStorage.getItem(k)); return v == null ? def : v; } catch (e) { return def; } }
  function jset(k, v) { try { localStorage.setItem(k, JSON.stringify(v)); return true; } catch (e) { return false; } }
  function load() { return jget(KEY, {}); }
  function save(o) { return jset(KEY, o); }
  function cache() { var c = jget(CACHE, null); return c && c.data ? c : { data: {}, time: 0 }; }
  function url() { return String(window.SHEET_URL || '').trim(); }
  function status(msg, ok) { Shared.status = msg; if (typeof window.onSharedStatus === 'function') window.onSharedStatus(msg, ok); }

  // One-time migration of pharmacies added in the older versions
  (function migrate() {
    try {
      if (localStorage.getItem(KEY) !== null) return;
      var c = {};
      var p1 = localStorage.getItem('maruf_custom_schedule_v2');
      if (p1) { var m = JSON.parse(p1); for (var k in m) { if (!BASE[k]) c[k] = { region: m[k].region, driver: m[k].driver || '' }; } }
      var p2 = localStorage.getItem('p2_custom_regions');
      if (p2) {
        var m2 = JSON.parse(p2);
        for (var k2 in m2) {
          if (!BASE[k2] || BASE[k2].region !== m2[k2]) c[k2] = { region: m2[k2], driver: (c[k2] && c[k2].driver) || (BASE[k2] ? BASE[k2].driver : '') };
        }
      }
      localStorage.setItem(KEY, JSON.stringify(c));
    } catch (e) {}
  })();

  function post(payload) {
    payload.key = Shared.getKey();
    return fetch(url(), { method: 'POST', body: JSON.stringify(payload) }).then(function (r) { return r.json(); });
  }

  var Shared = window.Shared = {
    status: '',
    getKey: function () { try { return localStorage.getItem(WKEY) || ''; } catch (e) { return ''; } },
    setKey: function (k) { try { localStorage.setItem(WKEY, String(k || '').trim()); } catch (e) {} },
    online: function () { return !!url(); },

    // final list = BASE + online Google Sheet + changes waiting on this computer
    merged: function () {
      var out = {}, k, layers = [cache().data, load()];
      var cc = cache();
      if (!((window.SHEET_ONLY || cc.complete) && Object.keys(cc.data).length > 0)) {
        for (k in BASE) out[k] = { region: BASE[k].region, driver: BASE[k].driver || '' };
      }
      layers.forEach(function (L) {
        for (k in L) {
          if (L[k] && L[k].removed) delete out[k];
          else if (L[k] && L[k].region) out[k] = { region: L[k].region, driver: L[k].driver || '' };
        }
      });
      return out;
    },

    custom: load,
    sheetData: function () { return cache().data; },
    baseCount: function () { return Object.keys(BASE).length; },
    sheetCount: function () { return Object.keys(cache().data).length; },
    pendingCount: function () { return Object.keys(load()).length; },

    // Save locally at once, then send online. driver === undefined keeps the existing driver.
    set: function (code, region, driver) {
      var c = load();
      var prev = (c[code] && !c[code].removed) ? c[code] : ((cache().data[code] && !cache().data[code].removed) ? cache().data[code] : (BASE[code] || {}));
      c[code] = { region: String(region).toUpperCase(), driver: driver === undefined ? (prev.driver || '') : String(driver).toUpperCase() };
      save(c);
      return Shared.push(code);
    },
    remove: function (code) {
      var c = load();
      if (BASE[code] || cache().data[code]) c[code] = { removed: true }; else delete c[code];
      save(c);
      return c[code] ? Shared.push(code) : Promise.resolve(true);
    },

    // Send one waiting change to the Google Sheet
    push: function (code) {
      var e = load()[code];
      if (!e) return Promise.resolve(true);
      if (!url()) { status('Saved on this computer only (online list is not set up)', false); return Promise.resolve(false); }
      if (!Shared.getKey()) { status('Saved on this computer. Enter the secret key on the Home page to send it online.', false); return Promise.resolve(false); }
      var payload = e.removed ? { action: 'remove', code: code } : { action: 'set', code: code, region: e.region, driver: e.driver };
      return post(payload).then(function (j) {
        if (j && j.ok) {
          var c2 = load(); delete c2[code]; save(c2);
          var ch = cache();
          ch.data[code] = e.removed ? { region: '', driver: '', removed: true } : { region: e.region, driver: e.driver, removed: false };
          jset(CACHE, ch);
          status('Saved online \u2714 (visible on all computers)', true);
          return true;
        }
        status('Online save failed: ' + ((j && j.error) || 'unknown') + '. Kept on this computer.', false);
        return false;
      }).catch(function () {
        status('No internet: saved on this computer, it will be sent online later.', false);
        return false;
      });
    },

    // Send everything that is waiting on this computer
    pushAll: function () {
      var keys = Object.keys(load());
      var done = 0;
      return keys.reduce(function (p, k) {
        return p.then(function () { return Shared.push(k).then(function (ok) { if (ok) done++; }); });
      }, Promise.resolve()).then(function () { return done; });
    },

    // Download the online list, then send anything waiting
    sync: function () {
      if (!url()) { status('Online list is not set up yet (see config.js). Using the built-in list.', false); return Promise.resolve(false); }
      return fetch(url() + (url().indexOf('?') < 0 ? '?' : '&') + 't=' + Date.now())
        .then(function (r) { return r.json(); })
        .then(function (j) {
          if (!j || !j.ok) throw new Error('bad reply');
          jset(CACHE, { data: j.data, time: Date.now(), complete: !!j.complete });
          var go = Shared.getKey() && Shared.pendingCount() ? Shared.pushAll() : Promise.resolve(0);
          return go.then(function () {
            if (!Shared.pendingCount()) status('Online list loaded \u2714 ' + new Date().toLocaleTimeString(), true);
            return true;
          });
        })
        .catch(function () { status('Offline: using the last saved copy of the list.', false); return false; });
    },

    // One-time: copy the built-in list into the Google Sheet (existing sheet rows are NOT overwritten)
    uploadBase: function () {
      if (!url()) return Promise.reject(new Error('Online list is not set up (config.js)'));
      if (!Shared.getKey()) return Promise.reject(new Error('Save the secret key first'));
      var items = Object.keys(BASE).map(function (k) { return { code: k, region: BASE[k].region, driver: BASE[k].driver || '' }; });
      return post({ action: 'bulk', items: items, skipExisting: true }).then(function (j) {
        if (!j || !j.ok) throw new Error(j && j.error === 'Bad pharmacy code' ? 'The Google script is the OLD version. Paste the new Code.gs in Apps Script and deploy a New version first.' : ((j && j.error) || 'Upload failed'));
        return Shared.sync().then(function () { return j; });
      });
    },

    // Backup = everything online + everything waiting on this computer
    exportJSON: function () {
      var all = {}, k, a = cache().data, b = load();
      for (k in a) all[k] = a[k];
      for (k in b) all[k] = b[k];
      return JSON.stringify({ app: 'logistics-tools', version: 1, saved: new Date().toISOString(), custom: all }, null, 2);
    },
    importObj: function (obj) {
      if (!obj || typeof obj.custom !== 'object') throw new Error('This is not a valid backup file');
      var c = load(), n = 0;
      for (var k in obj.custom) {
        var v = obj.custom[k];
        if (!/^[A-Z]\d{3,4}$/.test(k) || !v) continue;
        if (v.removed) c[k] = { removed: true };
        else if (v.region) c[k] = { region: String(v.region).toUpperCase(), driver: String(v.driver || '').toUpperCase() };
        else continue;
        n++;
      }
      save(c);
      return n;
    }
  };
})();
